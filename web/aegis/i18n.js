// Aegis Web Console — user-facing text.
//
// Every string the browser shows goes through `t(key, vars)`. Two dictionaries
// are kept in lockstep (a test asserts it): `zh` is the default, `en` is the
// alternative. Protocol values (event types, statuses, node types, tool names,
// error codes) are NOT translated: they are shown as emitted, with a localized
// label next to them where the UI adds one.
//
// The choice is a display preference in this browser only (like the theme). It
// is never task state, never sent to the Host and never part of the EventLog.

const STORAGE_KEY = "aegis.lang";

export const LANGS = Object.freeze([
    { id: "zh", label: "中文" },
    { id: "en", label: "English" },
]);

function detect() {
    try {
        const saved = globalThis.localStorage?.getItem(STORAGE_KEY);

        if (saved === "zh" || saved === "en") {
            return saved;
        }
    } catch {
        // private mode: fall through to the default
    }

    return "zh";
}

let current = detect();
const listeners = new Set();

// Apply the resolved language to the document before the first render, so the
// HTML `lang` attribute and a saved choice never disagree.
if (typeof document !== "undefined") {
    document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
}

export function getLang() {
    return current;
}

export function setLang(next) {
    if (next !== "zh" && next !== "en") {
        return;
    }

    if (next === current) {
        return;
    }

    current = next;

    try {
        globalThis.localStorage?.setItem(STORAGE_KEY, next);
    } catch {
        // the preference is best effort
    }

    if (typeof document !== "undefined") {
        document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
    }

    for (const listener of listeners) {
        listener(next);
    }
}

export function subscribeLang(listener) {
    listeners.add(listener);

    return () => listeners.delete(listener);
}

/** Translate one key. `{name}` placeholders are filled from `vars`. */
export function t(key, vars) {
    const row = DICT[current]?.[key] ?? DICT.en[key] ?? key;

    if (typeof row === "function") {
        return row(vars ?? {});
    }

    if (!vars) {
        return row;
    }

    return row.replace(/\{(\w+)\}/g, (_, name) =>
        vars[name] === undefined ? `{${name}}` : String(vars[name]),
    );
}

/** Localized label for a Host/work-cycle status value; the raw value stays visible as a title. */
export function statusLabel(value) {
    const key = `status.${value}`;
    const label = DICT[current]?.[key] ?? DICT.en[key];

    return label ?? value ?? "";
}

/** Localized label for a tool action status (raw value stays in the details). */
export function actionStatusLabel(value) {
    const key = `actionStatus.${value}`;
    const label = DICT[current]?.[key] ?? DICT.en[key];

    return label ?? value ?? "";
}

/** Localized label for a knowledge retrieval status. */
export function retrievalLabel(value) {
    const key = `retrieval.${value}`;
    const label = DICT[current]?.[key] ?? DICT.en[key];

    return label ?? value ?? "";
}

/** Localized message for a known API error code, falling back to the server text. */
export function apiErrorMessage(error) {
    const code = error?.code;
    const key = code ? `err.${code}` : null;
    const localized = key ? (DICT[current]?.[key] ?? DICT.en[key]) : null;

    return localized ?? error?.message ?? String(error);
}

export function locale() {
    return current === "zh" ? "zh-CN" : "en-US";
}

